/* Системный промт. Источник правды — PROMPT.md рядом с репозиторием.
   Склеивается из четырёх блоков в строгом порядке: правила → профиль → задача → окружение.
   Кэш-барьеры стоят после первых двух: правила общие для всех, профиль свой у каждого.
   Один барьер после профиля не годится — любая запись в память рвала бы весь кэш. */

export const RULES=`Ты — ассистент задачника CLUTCH. Ты работаешь внутри карточки одной записи и помогаешь
довести её до конца: обсудить, разложить на шаги, написать текст, назначить срок, закрыть.

# Как ты отвечаешь

Обращайся на «ты». Отвечай на языке, на котором пользователь ведёт разговор; короткие реплики
вроде «ok» или «thanks» язык не меняют.
Пиши настолько коротко, насколько можно без потери сути: убирай вступления, не пересказывай
вопрос, не подводи итог тому, что только что сказал. Жёсткого потолка длины нет — если вопрос
требует развёрнутого ответа, дай его, но каждая фраза должна нести новое.
Не начинай ответ с «Конечно», «Отлично», «Хороший вопрос». Не хвали пользователя за вопрос.
Не извиняйся дважды за одну ошибку.
Разметка разрешена и поддерживается: абзацы, списки, жирный, \`код\`, блоки кода, заголовки,
таблицы и ссылки. Колонка узкая, поэтому заголовки — только когда ответ действительно делится
на части, а в таблице не больше трёх столбцов и коротких ячеек. Эмодзи не используй.
Не выдумывай фактов о задаче. Если чего-то не знаешь — спроси или скажи, что не знаешь.
Не утверждай, что сделал то, чего не делал: письма ты не отправляешь, счета не оплачиваешь,
встречи не назначаешь. Менять записи ты пока тоже не умеешь — можешь только написать текст;
если просят изменить задачу, скажи, что это делается кнопками, и подскажи какими.

# Насколько подробно

Смотри на тип записи.
— Обычная задача («купить лампочки», «оплатить хостинг»): работай как исполнитель. Коротко,
  по делу, без наводящих вопросов. Один-два абзаца.
— Проект (у записи есть шаги): здесь можно рассуждать. Спорь с планом, если он плохой,
  предлагай порядок, замечай, что блокирует остальное.
— Если в снимке есть строка «открыт из шага», пользователь пришёл из конкретного шага:
  отвечай в контексте всего проекта, но говори про этот шаг.
Если вопрос вообще не про задачу — просто отвечай на него как обычный собеседник, с теми же
требованиями к краткости. Не напоминай, что ты «ассистент задачника», и не возвращай разговор
к задаче силой. Если из ответа явно следует новое дело, можешь одной фразой предложить завести
задачу.

# Инициатива

Максимум одно предложение сверх ответа, и только если оно уместно: поставить срок задаче без
срока, разбить на шаги задачу, которая явно из нескольких частей, закрыть задачу, которая по
переписке уже сделана. Одно предложение на сообщение, не повторяй его, если отказали.
Не подгоняй, не мотивируй, не оценивай, много ли у пользователя задач.

# Даты

Сегодня, часовой пояс и календарь на ближайшие дни даны ниже. Бери даты только оттуда, не
вычисляй сам и не считай от дат в переписке.
У срока есть только дата, без времени. Если названо время («завтра в три»), предложи поставить
дату, а время добавить в название задачи.
«Пятница», «в понедельник» — ближайший такой день после сегодня по календарю; если сегодня
и есть этот день, спроси, сегодня или через неделю. «На следующей неделе» без дня —
ближайший понедельник. «Через неделю» — тот же день недели через семь дней.
Если названная дата в прошлом, скажи об этом и переспроси.`;

const WD=['вс','пн','вт','ср','чт','пт','сб'];
const WD_FULL=['воскресенье','понедельник','вторник','среда','четверг','пятница','суббота'];
const MON=['января','февраля','марта','апреля','мая','июня','июля','августа','сентября','октября','ноября','декабря'];

/* Календарь строит сервер, а не модель: дни недели она считает плохо.
   Дата «сегодня» приходит от клиента — у него и у воркера сутки могут не совпасть. */
export function calendar(today,days=10){
 const base=new Date(today+'T00:00:00Z'), out=[];
 for(let i=0;i<days;i++){
  const d=new Date(base.getTime()+i*864e5);
  const iso=d.toISOString().slice(0,10);
  out.push('  '+WD[d.getUTCDay()]+' '+iso+(i===0?' — сегодня':i===1?' — завтра':''));
 }
 return out.join('\n');
}
export function longDate(today){
 const d=new Date(today+'T00:00:00Z');
 return WD_FULL[d.getUTCDay()]+', '+d.getUTCDate()+' '+MON[d.getUTCMonth()]+' '+d.getUTCFullYear();
}

const cut=(s,n)=>String(s==null?'':s).slice(0,n);
const size=n=>!n?'0 Б':n<1024?n+' Б':n<1048576?(n/1024).toFixed(n<10240?1:0)+' КБ':(n/1048576).toFixed(1)+' МБ';

/* Снимок задачи пересобирается на каждый запрос — чат всегда говорит о том,
   что человек видит на экране. Формат описан в PROMPT.md, блок 3. */
export function taskBlock(t){
 const L=['<task id="'+cut(t.id,16)+'">'];
 L.push('название: '+cut(t.title,300));
 L.push('тип: '+cut(t.kind||'задача',40));
 L.push('срок: '+(t.due?cut(t.due,10)+(t.dueWord?' ('+cut(t.dueWord,30)+')':''):'без срока'));
 const steps=Array.isArray(t.steps)?t.steps.slice(0,60):[];
 if(t.isProject){
  const closed=steps.filter(s=>s.done).length;
  L.push('состояние: '+(t.done?'выполнен':'открыт')+', '+closed+' из '+steps.length+' шагов закрыты');
 }else{
  L.push('состояние: '+(t.done?'выполнена'+(t.doneWord?' '+cut(t.doneWord,40):''):'открыта'));
  L.push('проект: '+(t.project?cut(t.project,300):'нет'));
 }
 if(t.fromStep)L.push('открыт из шага: ['+cut(t.fromStep,16)+']');
 if(t.isProject&&steps.length){
  L.push('шаги:');
  let firstOpen=true;
  for(const s of steps){
   const open=!s.done;
   L.push('  ['+cut(s.id,16)+'] '+cut(s.t,300)+' — '+(open?(firstOpen?'открыт, ближайший':'открыт'):'закрыт'));
   if(open)firstOpen=false;
  }
 }
 /* Содержимое в промт не уходит — только имена и размеры; читает модель по требованию.
    Исключение: маленькие файлы вкладываются целиком блоком <file> сразу после снимка. */
 const files=Array.isArray(t.files)?t.files.slice(0,20):[];
 if(files.length){
  L.push('файлы:');
  for(const f of files)L.push('  '+cut(f.name,200)+' — '+size(f.size)+(f.body!==undefined?', содержимое ниже':''));
 }else L.push('файлы: нет');
 L.push('</task>');
 return L.join('\n');
}

export function envBlock(today,tz,others){
 const L=['<now>','сегодня: '+longDate(today),'часовой пояс: '+cut(tz||'UTC',60),'календарь:',calendar(today),'</now>'];
 const o=(Array.isArray(others)?others:[]).slice(0,20);
 if(o.length){
  L.push('<other-tasks>');
  for(const x of o){
   L.push('['+cut(x.id,16)+'] '+cut(x.t,300)+(x.isProject?' (проект)':'')+' — '+(x.due?cut(x.due,10):'без срока'));
  }
  L.push('</other-tasks>');
 }
 return L.join('\n');
}

/* Поле system — массив блоков. cache_control на первых двух: правила и профиль. */
export function buildSystem(b){
 const sys=[{type:'text',text:RULES,cache_control:{type:'ephemeral'}}];
 if(b.profile)sys.push({type:'text',text:'<profile>\n'+cut(b.profile,4000)+'\n</profile>',cache_control:{type:'ephemeral'}});
 if(b.summary)sys.push({type:'text',text:'<summary>\n'+cut(b.summary,4000)+'\n</summary>'});
 sys.push({type:'text',text:taskBlock(b.task||{})});
 for(const f of (b.task&&Array.isArray(b.task.files)?b.task.files:[]))
  if(f&&f.body!==undefined)sys.push({type:'text',text:'<file name="'+cut(f.name,200)+'">\n'+cut(f.body,4000)+'\n</file>'});
 sys.push({type:'text',text:envBlock(b.today,b.tz,b.others)});
 return sys;
}
